const LOCAL_STORAGE_KEY = 'marathi_remington_custom_passages';
const SAVED_RESULTS_KEY = 'marathi_remington_test_results';

/**
 * Get all custom passages saved by the user
 */
export function getStoredCustomPassages(): Passage[] {
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch {
    return [];
  }
}

/**
 * Save a new custom passage
 */
export function saveCustomPassage(passage: Omit<Passage, 'id' | 'isCustom' | 'createdAt'>): Passage {
  const customList = getStoredCustomPassages();
  const newPassage: Passage = {
    ...passage,
    id: 'custom-' + Date.now(),
    isCustom: true,
    category: 'कस्टम (Custom)',
    createdAt: new Date().toLocaleDateString('mr-IN'),
  };
  customList.unshift(newPassage);
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(customList));
  } catch (err) {
    console.error('Failed to save custom passage', err);
  }
  return newPassage;
}

/**
 * Delete a custom passage
 */
export function deleteCustomPassage(id: string): void {
  const customList = getStoredCustomPassages().filter((p) => p.id !== id);
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(customList));
  } catch (err) {
    console.error('Failed to delete custom passage', err);
  }
}

/**
 * Get combined list of default + user custom passages
 */
export function getAllPassages(): Passage[] {
  const customList = getStoredCustomPassages();
  return [...customList, ...DEFAULT_PASSAGES];
}

/**
 * Calculate word and character count for any raw Marathi text
 */
export function analyzeMarathiText(text: string): { wordCount: number; charCount: number; est30WpmMin: number; est40WpmMin: number } {
  const trimmed = text.trim();
  if (!trimmed) {
    return { wordCount: 0, charCount: 0, est30WpmMin: 0, est40WpmMin: 0 };
  }
  const words = trimmed.split(/\s+/).filter(Boolean);
  const wordCount = words.length;
  const charCount = trimmed.length;
  const est30WpmMin = Math.ceil(wordCount / 30);
  const est40WpmMin = Math.ceil(wordCount / 40);

  return { wordCount, charCount, est30WpmMin, est40WpmMin };
}
